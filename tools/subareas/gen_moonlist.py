"""Every Power Moon of each kingdom (SystemData/ShineInfo.szs) with its English name, for the Moon Names menu."""
import oead, sys, json, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from msbt import parse_msbt

R = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
KINGDOMS = [('CapWorldHomeStage', 'Cap'), ('WaterfallWorldHomeStage', 'Cascade'), ('SandWorldHomeStage', 'Sand'),
            ('ForestWorldHomeStage', 'Wooded'), ('LakeWorldHomeStage', 'Lake'), ('CloudWorldHomeStage', 'Cloud'),
            ('ClashWorldHomeStage', 'Lost'), ('CityWorldHomeStage', 'Metro'), ('SnowWorldHomeStage', 'Snow'),
            ('SeaWorldHomeStage', 'Seaside'), ('LavaWorldHomeStage', 'Luncheon'), ('BossRaidWorldHomeStage', 'Ruined'),
            ('SkyWorldHomeStage', 'Bowser'), ('MoonWorldHomeStage', 'Moon'), ('PeachWorldHomeStage', 'Mushroom'),
            ('Special1WorldHomeStage', 'Dark Side'), ('Special2WorldHomeStage', 'Darker Side')]

shine = oead.Sarc(oead.yaz0.decompress((R / 'SystemData/ShineInfo.szs').read_bytes()))
msg = oead.Sarc(oead.yaz0.decompress((R / 'LocalizedData/USen/MessageData/StageMessage.szs').read_bytes()))
msbt = {}


def name_of(stage, obj):
    if stage not in msbt:
        f = msg.get_file(stage + '.msbt')
        msbt[stage] = parse_msbt(bytes(f.data)) if f else {}
    return msbt[stage].get('ScenarioName_' + obj)


def esc(s):
    return s.replace('\\', '\\\\').replace('"', '\\"')


L = ['#pragma once', '', '// Generated by tools/subareas/gen_moonlist.py from SystemData/ShineInfo.szs and the USen stage messages',
     '', 'namespace btt {', '', 'struct MoonEntry {', '    const char* stage;', '    const char* objId;', '    const char* name;', '};',
     '', 'struct KingdomMoons {', '    const char* title;', '    const MoonEntry* moons;', '    int count;', '};', '']
tables = []
total = 0
wl = oead.Sarc(oead.yaz0.decompress((R / 'SystemData/WorldList.szs').read_bytes()))
worlds = {str(w['Name']): [str(st['name']) for st in w['StageList']] for w in oead.byml.from_binary(wl.get_file('WorldListFromDb.byml').data)}
order = {}
for home, title in KINGDOMS:
    # ShineInfo order first (the game's moon list order), then every other moon name of the kingdom's stages
    f = shine.get_file(f'ShineList_{home.replace("BossRaid", "Attack")}.byml')
    lst = oead.byml.from_binary(f.data)['ShineList'] if f else []
    moons, seen = [], set()
    for e in lst:
        stage, obj = str(e['StageName']), str(e['ObjId'])
        n = name_of(stage, obj)
        if n and (stage, obj) not in seen:
            seen.add((stage, obj)); moons.append((stage, obj, n.strip()))
    for stage in [home] + worlds.get(home, []):
        if stage not in msbt:
            mf = msg.get_file(stage + '.msbt')
            msbt[stage] = parse_msbt(bytes(mf.data)) if mf else {}
        for label, n in msbt[stage].items():
            if label.startswith('ScenarioName_') and n.strip():
                obj = label[len('ScenarioName_'):]
                if (stage, obj) not in seen:
                    seen.add((stage, obj)); moons.append((stage, obj, n.strip()))
    ident = 'sMoons' + home.replace('WorldHomeStage', '')
    L.append(f'inline constexpr MoonEntry {ident}[] = {{')
    for stage, obj, n in moons:
        L.append(f'    {{ "{stage}", "{obj}", "{esc(n)}" }},')
    L.append('};')
    tables.append((title, ident, len(moons)))
    total += len(moons)
L += ['', 'inline constexpr KingdomMoons sKingdomMoons[] = {']
for title, ident, n in tables:
    L.append(f'    {{ "{title}", {ident}, {n} }},')
L += ['};', '', '} // namespace btt', '']
out.write_bytes('\n'.join(L).encode('utf-8'))
print(total, [t[2] for t in tables])
